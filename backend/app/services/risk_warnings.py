def get_warning_for_clause(clause_type: str, risk_level: str) -> str:
    """
    Returns an Arabic warning message if the clause is high risk.
    
    Args:
        clause_type: The canonical clause type (one of 8 types).
        risk_level: The predicted risk level (low, medium, high).
        
    Returns:
        A warning text string if high risk, else empty string.
    """
    if risk_level.lower() == "high":
        return WARNING_TEMPLATES.get(clause_type, "تحذير: يحتوي هذا البند على مخاطر محتملة تتطلب مراجعة قانونية دقيقة.")
    return ""
